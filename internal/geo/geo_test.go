var errBoom = errors.New("boom")

// failAfterWriter accepts up to limit bytes, then fails every further write
// with a short write and err, like a broken pipe or full disk would.
type failAfterWriter struct {
	limit int
	n     int
	err   error
}

func (w *failAfterWriter) Write(p []byte) (int, error) {
	if w.n+len(p) <= w.limit {
		w.n += len(p)
		return len(p), nil
	}
	short := w.limit - w.n
	if short < 0 {
		short = 0
	}
	w.n = w.limit
	return short, w.err
}

func TestGenerateReturnsWriterError(t *testing.T) {
	small := &model.Report{Findings: []model.Finding{
		{Target: netip.MustParsePrefix("10.0.0.0/8"), Reasons: []string{"alpha"}},
	}}
	// big renders well past the 4 KiB bufio buffer, so writes to the
	// underlying writer fail mid-stream instead of only at flush time.
	big := &model.Report{Findings: make([]model.Finding, 500)}
	for i := range big.Findings {
		big.Findings[i] = model.Finding{
			Target:  netip.MustParsePrefix("10.0.0.0/8"),
			Reasons: []string{"alpha-reason", "beta-reason"},
		}
	}

	g := mustGenerator(t, geo.GeneratorConfig{VariableName: "$geo"})

	cases := []struct {
		name   string
		limit  int
		report *model.Report
	}{
		{name: "writer fails immediately", limit: 0, report: small},
		{name: "writer fails mid-stream", limit: 500, report: big},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			w := &failAfterWriter{limit: tc.limit, err: errBoom}
			err := g.Generate(w, fixedNow, tc.report, 0)
			if err == nil {
				t.Fatal("Generate: got nil error, want writer failure surfaced")
			}
			if !errors.Is(err, errBoom) {
				t.Errorf("Generate error %q should wrap the writer error %q", err, errBoom)
			}
		})
	}
}

