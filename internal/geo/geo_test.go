// fixedNow is the deterministic clock injected into Generator.Generate:
// 2026-01-02T03:04:05Z (RFC 3339: "2026-01-02T03:04:05Z").
func fixedNow() time.Time {
	return time.Date(2026, time.January, 2, 3, 4, 5, 0, time.UTC)
}

func mustGenerator(t *testing.T, cfg geo.GeneratorConfig) *geo.Generator {
	t.Helper()
	g, err := geo.NewGenerator(cfg)
	if err != nil {
		t.Fatalf("NewGenerator(%+v): unexpected error: %v", cfg, err)
	}
	if g == nil {
		t.Fatalf("NewGenerator(%+v): got nil generator with nil error", cfg)
	}
	return g
}

// generatedHeaderRe pins the structure of the "# Generated by" line: the
// generator's build identity (name, version, optionally a commit) framed by
// the fixed text. The identity is injected via ldflags at build time, so it is
// checked structurally here instead of being recomputed from internal/info.
var generatedHeaderRe = regexp.MustCompile(`\A# Generated by bandaid \S+( \S+)?\. DO NOT EDIT\.\n`)

// withoutHeader validates the generated-by line and returns the rest of the
// output, whose parts are all fixed and asserted against hand-written literals.
func withoutHeader(t *testing.T, out string) string {
	t.Helper()
	loc := generatedHeaderRe.FindStringIndex(out)
	if loc == nil {
		first := out
		if i := strings.IndexByte(out, '\n'); i >= 0 {
			first = out[:i]
		}
		t.Fatalf("generated-by line does not match %v; got %q", generatedHeaderRe, first)
	}
	return out[loc[1]:]
}

