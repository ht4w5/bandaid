func TestGenerateRendersGoldenGeoBlock(t *testing.T) {
	report := &model.Report{Findings: []model.Finding{
		{Target: netip.MustParsePrefix("10.0.0.0/8"), Reasons: []string{"alpha", "beta"}},
		{Target: netip.MustParsePrefix("192.0.2.0/24"), Reasons: []string{"probe"}},
		{Target: netip.MustParsePrefix("2001:db8::/32"), Reasons: []string{"v6", "scan"}},
	}}
	g := mustGenerator(t, geo.GeneratorConfig{
		VariableName:        "$geo",
		AddressVariableName: "$arg_remote_addr",
		DefaultString:       "none",
	})

	var buf bytes.Buffer
	if err := g.Generate(&buf, fixedNow, report, 0xdeadbeef); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	// Expected block written by hand from the nginx geo syntax:
	//
	//   geo [$address] $variable {
	//       default <value>;
	//       <network> <value>;
	//       ...
	//   }
	//
	// Entry values are the finding value contract (reasons joined with ":")
	// rendered with Go %q quoting. Hash 0xdeadbeef renders as hex "deadbeef".
	const want = `# Time of generation: 2026-01-02T03:04:05Z
# Report hash: deadbeef
geo $arg_remote_addr $geo {
    default "none";
    10.0.0.0/8 "alpha:beta";
    192.0.2.0/24 "probe";
    2001:db8::/32 "v6:scan";
}
`

	got := withoutHeader(t, buf.String())
	if got != want {
		t.Errorf("geo block mismatch\ngot:\n%s\nwant:\n%s", got, want)
	}
}

func TestGenerateHeaderIdentifiesGenerator(t *testing.T) {
	g := mustGenerator(t, geo.GeneratorConfig{VariableName: "$geo"})

	var buf bytes.Buffer
	if err := g.Generate(&buf, fixedNow, &model.Report{}, 0); err != nil {
		t.Fatalf("Generate: %v", err)
	}

	end := strings.IndexByte(buf.String(), '\n') + 1
	if end == 0 {
		t.Fatalf("output has no header line: %q", buf.String())
	}
	first := buf.String()[:end]
	if !generatedHeaderRe.MatchString(first) {
		t.Errorf("generated-by line %q does not match %v", strings.TrimSuffix(first, "\n"), generatedHeaderRe)
	}
}

